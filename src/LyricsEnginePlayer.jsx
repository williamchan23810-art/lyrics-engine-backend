// src/LyricsEnginePlayer.jsx
import React, { useState, useEffect } from 'react';
import { Film, Edit3, Type, Music, BookOpen, Check, Sparkles, Copy } from 'lucide-react';
import StoryboardModal from './StoryboardModal';
import LyricsEditorModal from './LyricsEditorModal';
import AutoGeneratorModal from './AutoGeneratorModal';
import { copyToNotebookClipboard } from './NotebookExporter';

const LyricsEnginePlayer = ({ 
  trackData: initialTrackData, 
  apiBaseUrl = '' 
}) => {
  const [trackData, setTrackData] = useState(initialTrackData);
  const [storyboardData, setStoryboardData] = useState(null);
  const [fontStyle, setFontStyle] = useState('sans');
  
  // Modal & Clipboard Controls
  const [isStoryboardOpen, setIsStoryboardOpen] = useState(false);
  const [isEditorOpen, setIsEditorOpen] = useState(false);
  const [isAutoGrabOpen, setIsAutoGrabOpen] = useState(false);
  const [copiedNotebook, setCopiedNotebook] = useState(false);
  const [copiedRawLyrics, setCopiedRawLyrics] = useState(false);

  useEffect(() => {
    if (initialTrackData) {
      setTrackData(initialTrackData);
    }
  }, [initialTrackData]);

  const handleSaveFormattedLyrics = (newLyrics) => {
    setTrackData((prev) => ({ ...prev, lyrics: newLyrics }));
  };

  const handleSongAutoGenerated = (generatedData) => {
    const rawLines = generatedData.lines || generatedData.lyrics || [];

    const normalizedLyrics = rawLines.map((line, idx) => {
      const startTimeSec = typeof line.startTime === 'number' 
        ? line.startTime 
        : (line.startTimeMs ? line.startTimeMs / 1000 : idx * 3.5);

      const endTimeSec = typeof line.endTime === 'number' 
        ? line.endTime 
        : (line.endTimeMs ? line.endTimeMs / 1000 : (idx + 1) * 3.5);

      return {
        lineIndex: idx,
        startTime: startTimeSec,
        endTime: endTimeSec,
        text: line.text || line.originalText || '',
        tokens: line.tokens || []
      };
    });

    setTrackData({
      trackId: generatedData.trackId || Date.now().toString(),
      title: generatedData.title || "Untitled Track",
      artist: generatedData.artist || "Unknown Artist",
      lyrics: normalizedLyrics
    });

    if (generatedData.storyboard) {
      setStoryboardData(generatedData.storyboard);
    }
  };

  const handleCopyRawLyrics = () => {
    if (!trackData?.lyrics || trackData.lyrics.length === 0) return;
    const plainText = trackData.lyrics.map((l) => l.text).join('\n');
    navigator.clipboard.writeText(plainText);
    setCopiedRawLyrics(true);
    setTimeout(() => setCopiedRawLyrics(false), 2000);
  };

  const handleExportToNotebook = async () => {
    const success = await copyToNotebookClipboard(trackData, storyboardData);
    if (success) {
      setCopiedNotebook(true);
      setTimeout(() => setCopiedNotebook(false), 2500);
    }
  };

  const formatTimestamp = (sec) => {
    const totalSec = Math.floor(sec || 0);
    const mins = Math.floor(totalSec / 60);
    const secs = totalSec % 60;
    return `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
  };

  const fontClass = fontStyle === 'cambria' ? 'font-serif' : 'font-sans';

  return (
    <div className={`h-screen w-screen bg-slate-950 text-slate-100 flex flex-col overflow-hidden ${fontClass}`}>
      
      {/* Top Navigation & Action Toolbar */}
      <header className="flex flex-wrap items-center justify-between p-3.5 bg-slate-900/90 border-b border-slate-800 backdrop-blur-md gap-2 z-20 shrink-0">
        <div className="flex items-center gap-2.5">
          <div className="p-1.5 bg-amber-400/10 rounded-lg text-amber-400">
            <Music size={18} />
          </div>
          <div>
            <h1 className="text-sm font-bold text-amber-400 leading-tight">
              {trackData?.title || "Karaoke & Songs Appreciation"}
            </h1>
            <p className="text-[11px] text-slate-400">
              {trackData?.artist || "William H Chan Studio"}
            </p>
          </div>
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-1.5 flex-wrap">
          <button
            onClick={() => setIsAutoGrabOpen(true)}
            className="flex items-center gap-1.5 bg-amber-400 hover:bg-amber-300 text-slate-950 px-3 py-1.5 rounded-lg text-xs font-bold transition shadow-lg shadow-amber-400/20 cursor-pointer"
          >
            <Sparkles size={14} />
            <span>Start Auto-Grab</span>
          </button>

          <button
            onClick={() => setIsStoryboardOpen(true)}
            className="flex items-center gap-1 bg-amber-500/15 hover:bg-amber-500/25 text-amber-300 border border-amber-500/30 px-3 py-1.5 rounded-lg text-xs font-semibold transition cursor-pointer"
          >
            <Film size={13} />
            <span>AI Storyboard</span>
          </button>

          <button
            onClick={handleCopyRawLyrics}
            disabled={!trackData?.lyrics || trackData.lyrics.length === 0}
            className="flex items-center gap-1 bg-slate-800 hover:bg-slate-700 text-slate-200 disabled:opacity-40 px-2.5 py-1.5 rounded-lg text-xs font-semibold border border-slate-700 transition cursor-pointer"
          >
            {copiedRawLyrics ? <Check size={13} className="text-emerald-400" /> : <Copy size={13} className="text-amber-400" />}
            <span>{copiedRawLyrics ? 'Copied' : 'Copy Lyrics'}</span>
          </button>

          <div className="flex items-center gap-1 bg-slate-800 border border-slate-700 rounded-lg px-2 py-1.5 text-xs text-slate-300">
            <Type size={13} className="text-amber-400" />
            <select
              value={fontStyle}
              onChange={(e) => setFontStyle(e.target.value)}
              className="bg-transparent text-xs text-slate-200 focus:outline-none cursor-pointer"
            >
              <option value="sans" className="bg-slate-900 text-slate-200">Sans-Serif</option>
              <option value="cambria" className="bg-slate-900 text-slate-200">Cambria</option>
            </select>
          </div>

          <button
            onClick={() => setIsEditorOpen(true)}
            className="flex items-center gap-1 bg-slate-800 hover:bg-slate-700 text-slate-200 px-2.5 py-1.5 rounded-lg text-xs font-semibold border border-slate-700 transition cursor-pointer"
          >
            <Edit3 size={13} className="text-amber-400" />
            <span>Edit</span>
          </button>

          <button
            onClick={handleExportToNotebook}
            className="flex items-center gap-1 bg-slate-800 hover:bg-slate-700 text-slate-200 px-2.5 py-1.5 rounded-lg text-xs font-semibold border border-slate-700 transition cursor-pointer"
          >
            {copiedNotebook ? <Check size={13} className="text-emerald-400" /> : <BookOpen size={13} className="text-amber-400" />}
            <span>{copiedNotebook ? 'Copied!' : 'Export Notebook'}</span>
          </button>
        </div>
      </header>

      {/* Main Full-Screen Lyrics Stage */}
      <main className="flex-1 overflow-y-auto overflow-x-hidden p-6 flex flex-col items-center [scrollbar-width:none] [-ms-overflow-style:none] [&::-webkit-scrollbar]:hidden select-text">
        {!trackData?.lyrics || trackData.lyrics.length === 0 ? (
          <div className="flex flex-col items-center justify-center my-auto space-y-2 text-slate-500">
            <Music size={42} className="stroke-1 opacity-40" />
            <p className="text-xs">No lyrics loaded. Click "Start Auto-Grab" to search.</p>
          </div>
        ) : (
          <div className="w-full max-w-3xl space-y-1.5 py-4 text-center">
            {trackData.lyrics.map((line, idx) => (
              <div
                key={idx}
                className="group py-1 px-3 rounded-lg flex items-center justify-center gap-3 hover:bg-slate-900/60 transition-colors"
              >
                {/* Subtle Timestamp Tag */}
                <span className="text-[10px] font-mono text-slate-600 group-hover:text-amber-400/70 transition-colors select-none">
                  {formatTimestamp(line.startTime)}
                </span>

                {/* Lyrics with Phonetic Tokens */}
                <div className="flex flex-wrap items-center justify-center gap-x-1 gap-y-0.5">
                  {line.tokens && line.tokens.length > 0 ? (
                    line.tokens.map((token, tIdx) => (
                      <ruby key={tIdx} className="text-sm md:text-base text-slate-200 inline-flex flex-col items-center">
                        <span className="leading-snug">{token.char}</span>
                        {token.phonetic && (
                          <rt className="text-[9px] text-amber-300/80 font-normal tracking-tight">
                            {token.phonetic}
                          </rt>
                        )}
                      </ruby>
                    ))
                  ) : (
                    <span className="text-sm md:text-base text-slate-200 font-normal leading-snug">
                      {line.text}
                    </span>
                  )}
                </div>
              </div>
            ))}
          </div>
        )}
      </main>

      {/* Modals */}
      <AutoGeneratorModal 
        isOpen={isAutoGrabOpen} 
        onClose={() => setIsAutoGrabOpen(false)} 
        onSongGenerated={handleSongAutoGenerated} 
        apiBaseUrl={apiBaseUrl} 
      />
      <StoryboardModal 
        trackData={trackData} 
        isOpen={isStoryboardOpen} 
        onClose={() => setIsStoryboardOpen(false)} 
        onStoryboardGenerated={(data) => setStoryboardData(data)} 
        apiBaseUrl={apiBaseUrl} 
      />
      <LyricsEditorModal 
        trackData={trackData} 
        isOpen={isEditorOpen} 
        onClose={() => setIsEditorOpen(false)} 
        onSaveLyrics={handleSaveFormattedLyrics} 
        apiBaseUrl={apiBaseUrl} 
      />
    </div>
  );
};

export default LyricsEnginePlayer;
